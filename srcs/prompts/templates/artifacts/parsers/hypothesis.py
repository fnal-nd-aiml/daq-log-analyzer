"""Hypothesis parser for LLM response parsing.

Parses hypothesis generation responses and converts them to
domain models and WorkBinder artifacts.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, List

from pydantic import BaseModel

from srcs.models import Hypothesis
from srcs.workbinder.artifacts_types import HypothesisArtifact

from .base import BaseParser
from .json_utils import parse_json_response

if TYPE_CHECKING:
    pass


class HypothesisItem(BaseModel):
    """Single hypothesis from LLM response.

    Contains all fields returned by the LLM during hypothesis generation,
    including fields that were previously discarded (category, confirming/
    refuting evidence designs).

    Attributes:
        description: Hypothesis description text
        category: Category classification (timing, configuration, etc.)
        prior: Prior probability estimate (0.0-1.0)
        confirming_evidence: Description of evidence that would confirm
        refuting_evidence: Description of evidence that would refute
    """

    description: str
    category: str
    prior: float
    confirming_evidence: str = ""
    refuting_evidence: str = ""


class HypothesisResponse(BaseModel):
    """LLM response for hypothesis generation.

    Contains a list of hypothesis items generated by the LLM.
    """

    hypotheses: List[HypothesisItem]


class HypothesisParser(BaseParser[HypothesisResponse, Hypothesis, HypothesisArtifact]):
    """Parser for hypothesis generation LLM responses.

    Implements two-stage conversion:
    1. LLM Response -> Hypothesis domain model
    2. Hypothesis -> HypothesisArtifact

    Preserves additional fields (category, confirming/refuting evidence)
    that were previously discarded during parsing.

    Example:
        >>> parser = HypothesisParser()
        >>> response = parser.parse_llm_response(raw_json)
        >>> for item in response.hypotheses:
        ...     hypothesis = parser.to_domain_model(
        ...         item, source_prefix="fresh", max_prior=0.3
        ...     )
        ...     artifact = parser.to_artifact(hypothesis, "Theorist", 1)
    """

    def parse_llm_response(self, raw_json: str) -> HypothesisResponse:
        """Parse raw LLM response JSON into HypothesisResponse.

        Args:
            raw_json: Raw JSON string from LLM

        Returns:
            Parsed HypothesisResponse

        Raises:
            ValueError: If JSON cannot be parsed
        """
        return parse_json_response(raw_json, HypothesisResponse)

    def to_domain_model(
        self,
        item: HypothesisItem,
        source_prefix: str = "fresh",
        max_prior: float | None = None,
        **context: object,
    ) -> Hypothesis:
        """Convert HypothesisItem to Hypothesis domain model.

        Args:
            item: HypothesisItem from LLM response
            source_prefix: Source prefix (default "fresh")
            max_prior: Maximum prior value to cap at (optional)
            **context: Additional context (unused)

        Returns:
            Hypothesis domain model instance

        Note:
            The category from the LLM response is incorporated into
            the source field as "source_prefix:category".
        """
        prior_value = item.prior
        if max_prior is not None:
            prior_value = min(max_prior, item.prior)

        return Hypothesis(
            description=item.description,
            source=f"{source_prefix}:{item.category}",
            prior=prior_value,
            score=prior_value,  # Initialize score from prior
            # Extended fields preserved for artifact conversion
            category=item.category,
            confirming_evidence_design=item.confirming_evidence or None,
            refuting_evidence_design=item.refuting_evidence or None,
        )

    def to_artifact(
        self,
        domain_model: Hypothesis,
        created_by: str,
        phase: int,
        rank: int = 0,
        llm_request_id: str | None = None,
        **kwargs: object,
    ) -> HypothesisArtifact:
        """Convert Hypothesis to HypothesisArtifact.

        Args:
            domain_model: Hypothesis domain model
            created_by: Persona name creating the artifact
            phase: Investigation phase number
            rank: Hypothesis rank (default 0)
            llm_request_id: Optional LLM request ID for traceability
            **kwargs: Additional artifact fields

        Returns:
            HypothesisArtifact instance
        """
        return HypothesisArtifact(
            description=domain_model.description,
            source=domain_model.source,
            prior_probability=domain_model.prior,
            score=domain_model.score,
            rank=rank,
            created_by=created_by,
            phase=phase,
            llm_request_id=llm_request_id,
            # Extended fields
            category=getattr(domain_model, "category", None),
            confirming_evidence=getattr(domain_model, "confirming_evidence_design", None),
            refuting_evidence=getattr(domain_model, "refuting_evidence_design", None),
        )

    def parse_and_convert(
        self,
        raw_json: str,
        source_prefix: str = "fresh",
        max_prior: float | None = None,
        exclude_descriptions: set[str] | None = None,
    ) -> list[Hypothesis]:
        """Convenience method to parse and convert in one step.

        Args:
            raw_json: Raw JSON string from LLM
            source_prefix: Source prefix for hypotheses
            max_prior: Maximum prior value to cap at
            exclude_descriptions: Set of descriptions to exclude (dedup)

        Returns:
            List of Hypothesis domain models
        """
        exclude = exclude_descriptions or set()
        response = self.parse_llm_response(raw_json)

        hypotheses = []
        for item in response.hypotheses:
            if item.description not in exclude:
                hypothesis = self.to_domain_model(
                    item, source_prefix=source_prefix, max_prior=max_prior
                )
                hypotheses.append(hypothesis)

        return hypotheses
